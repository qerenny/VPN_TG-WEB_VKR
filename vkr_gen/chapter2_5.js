const mm    = (v) => Math.round(v / 25.4 * 1440);
const LEFT  = mm(30);
const RIGHT = mm(15);
const TOP   = mm(20);
const BOT   = mm(20);
const IND   = mm(12.5);
const FONT  = "Times New Roman";
const SZ    = 28;
const SP    = { line: 360, lineRule: "auto", before: 0, after: 0 };

function r(text, opts = {}) {
  return new TextRun({ text, font: FONT, size: SZ, ...opts });
}

function p(runs, opts = {}) {
  const ch = typeof runs === 'string' ? [r(runs)] : runs;
  return new Paragraph({
    children: ch,
    spacing: SP,
    indent: { firstLine: IND },
    alignment: AlignmentType.BOTH,
    ...opts,
  });
}

function h1(text) {
  return new Paragraph({
    children: [r(text, { bold: true, allCaps: true })],
    spacing: SP,
    indent: { firstLine: IND },
    pageBreakBefore: true,
    heading: HeadingLevel.HEADING_1,
  });
}

function h2(text) {
  return new Paragraph({
    children: [r(text, { bold: true })],
    spacing: SP,
    indent: { firstLine: IND },
    heading: HeadingLevel.HEADING_2,
  });
}

function figCaption(text) {
  return new Paragraph({
    children: [r(text)],
    spacing: SP,
    indent: { firstLine: 0 },
    alignment: AlignmentType.CENTER,
  });
}

function figPlaceholder(text) {
  return new Paragraph({
    children: [r(text, { italics: true })],
    spacing: SP,
    indent: { firstLine: 0 },
    alignment: AlignmentType.CENTER,
  });
}

const pageFooter = new Footer({
  children: [new Paragraph({
    alignment: AlignmentType.CENTER,
    children: [new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: SZ })],
    spacing: SP,
    indent: { firstLine: 0 },
  })],
});

