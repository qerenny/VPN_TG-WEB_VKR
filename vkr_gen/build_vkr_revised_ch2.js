function cellParagraph(text, isHeader) {
  return new Paragraph({
    children: [run(text, { size: TABLE_SIZE, bold: isHeader })],
    spacing: SPACING,
    indent: { firstLine: 0 },
    alignment: isHeader ? AlignmentType.CENTER : AlignmentType.LEFT,
  });
}

function makeTable(rows, widths) {
  const border = { style: BorderStyle.SINGLE, size: 4, color: "000000" };
  return new Table({
    width: { size: CONTENT_WIDTH, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((row, rowIndex) => new TableRow({
      children: row.map((value, colIndex) => new TableCell({
        borders: { top: border, bottom: border, left: border, right: border },
        verticalAlign: rowIndex === 0 ? VerticalAlign.CENTER : VerticalAlign.TOP,
        width: { size: widths[colIndex], type: WidthType.DXA },
        margins: { top: 60, bottom: 60, left: 90, right: 90 },
        children: [cellParagraph(value, rowIndex === 0)],
      })),
    })),
  });
}

function pngSize(filePath) {
  const buf = fs.readFileSync(filePath);
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function imageParagraph(filePath, maxWidthPx = 620) {
  const data = fs.readFileSync(filePath);
  const { width, height } = pngSize(filePath);
  const scale = width > maxWidthPx ? maxWidthPx / width : 1;
  const type = path.extname(filePath).replace(".", "") || "png";
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: SPACING,
    indent: { firstLine: 0 },
    children: [new ImageRun({
      data,
      type,
      transformation: {
        width: Math.round(width * scale),
        height: Math.round(height * scale),
      },
    })],
  });
}

