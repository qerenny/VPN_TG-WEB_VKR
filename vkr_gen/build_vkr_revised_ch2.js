function stripMarks(text) {
  return text.replace(/^\*\*/, "").replace(/\*\*$/, "").trim();
}

function parseFlatTable(lines, startIndex, spec) {
  const rows = [];
  let index = startIndex;
  while (index < lines.length) {
    const line = lines[index].trim();
    if (!line) {
      index += 1;
      continue;
    }
    if (
      line.startsWith("#") ||
      line.startsWith("**Таблица") ||
      line.startsWith("**Рисунок") ||
      line.startsWith("_[Рисунок")
    ) {
      break;
    }
    if (spec.stopPrefix && line.startsWith(spec.stopPrefix)) {
      break;
    }
    rows.push(line);
    index += 1;
  }
  const grouped = [];
  for (let i = 0; i < rows.length; i += spec.cols) {
    grouped.push(rows.slice(i, i + spec.cols));
  }
  return { table: makeTable(grouped, spec.widths), nextIndex: index };
}

function parseChapter2(markdown) {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const children = [];
  let index = 0;
  let firstH1 = false;

  while (index < lines.length) {
    const line = lines[index].trim();

    if (!line) {
      index += 1;
      continue;
    }

    if (line.startsWith("_[Рисунок")) {
      index += 1;
      continue;
    }

    if (line.startsWith("**Таблица")) {
      const title = stripMarks(line);
      children.push(caption(title));
      const spec = tableSpecs[title];
      if (!spec) {
        throw new Error(`Unknown table caption: ${title}`);
      }
      const parsed = parseFlatTable(lines, index + 1, spec);
      children.push(parsed.table);
      index = parsed.nextIndex;
      continue;
    }

    if (line.startsWith("**Рисунок")) {
      const title = stripMarks(line);
      const img = figureMap[title];
      if (img && fs.existsSync(img)) {
        children.push(imageParagraph(img));
      }
      children.push(caption(title));
      index += 1;
      continue;
    }

    if (line.startsWith("# ")) {
      children.push(h1(line.slice(2).trim(), !firstH1));
      firstH1 = true;
      index += 1;
      continue;
    }

    if (line.startsWith("## ")) {
      children.push(h2(line.slice(3).trim()));
      index += 1;
      continue;
    }

    if (line.startsWith("### ")) {
      children.push(h3(line.slice(4).trim()));
      index += 1;
      continue;
    }

    children.push(paragraph(line));
    index += 1;
  }

  return children;
}

