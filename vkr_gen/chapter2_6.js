const FONT  = "Times New Roman";
const SZ    = 28;
const SP    = { line: 360, lineRule: "auto", before: 0, after: 0 };

function r(text, opts = {}) {
  return new TextRun({ text, font: FONT, size: SZ, ...opts });
}

function p(runs, opts = {}) {
  const ch = typeof runs === 'string' ? [r(runs)] : runs;
  return new Paragraph({
    children: ch,
    spacing: SP,
    indent: { firstLine: IND },
    alignment: AlignmentType.BOTH,
    ...opts,
  });
}

function h1(text) {
  return new Paragraph({
    children: [r(text, { bold: true, allCaps: true })],
    spacing: SP,
    indent: { firstLine: IND },
    pageBreakBefore: true,
    heading: HeadingLevel.HEADING_1,
  });
}

function h2(text) {
  return new Paragraph({
    children: [r(text, { bold: true })],
    spacing: SP,
    indent: { firstLine: IND },
    heading: HeadingLevel.HEADING_2,
  });
}

function makeTable(rows, colWidths, headerRows = 1) {
  const total = colWidths.reduce((a, b) => a + b, 0);
  const brd = { style: BorderStyle.SINGLE, size: 4, color: "000000" };
  const brdAll = { top: brd, bottom: brd, left: brd, right: brd };
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: colWidths,
    rows: rows.map((row, ri) =>
      new TableRow({
        children: row.map((cell, ci) =>
          new TableCell({
            borders: brdAll,
            width: { size: colWidths[ci], type: WidthType.DXA },
            verticalAlign: VerticalAlign.TOP,
            margins: { top: 60, bottom: 60, left: 100, right: 100 },
            children: [new Paragraph({
              children: [r(cell, ri < headerRows ? { bold: true } : {})],
              spacing: SP,
              indent: { firstLine: 0 },
              alignment: AlignmentType.BOTH,
            })],
          })
        ),
      })
    ),
  });
}

function tableCaption(text) {
  return new Paragraph({
    children: [r(text)],
    spacing: SP,
    indent: { firstLine: 0 },
    alignment: AlignmentType.LEFT,
  });
}

